/**
 * v0.34.0: bundle the mobile/iPad web viewer (webclient/index.html) into a
 * JS module the main process can serve, WITHOUT reading a source-tree file
 * at runtime (which would break in the packaged asar — see AGENTS.md §21).
 *
 * It emits main/webclientHtml.js = `module.exports = "<html as a JSON
 * string>";`. The electron build then compiles that into
 * dist-electron/main/webclientHtml.js, and the server does
 * `require('../webclientHtml')` to serve the page at GET /m.
 *
 * Fuel F1: the same for the phone fuel page served at GET /f. Its source is
 * three files — webclient/fuel/index.html plus logic.js (pure, unit-tested
 * under node:test) and app.js (the screens) — and each INLINE marker in the
 * HTML (a comment naming one of the files) is replaced by that file, so the
 * page stays one self-contained document. Output: main/fuelWebclientHtml.js.
 *
 * Run automatically in `predist` (so release builds always carry the
 * latest pages), and any time you edit a file under webclient/:
 *   node scripts/build-webclient.js
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const INLINE_RE = /\/\*@INLINE ([\w.-]+)\*\//g;

/** A phone page: webclient/<dir>/index.html with every INLINE marker replaced by that file. */
function buildInlineHtml(dirName, root = ROOT) {
  const dir = path.join(root, 'webclient', dirName);
  const shell = fs.readFileSync(path.join(dir, 'index.html'), 'utf8');
  const html = shell.replace(INLINE_RE, (_, name) => {
    const code = fs.readFileSync(path.join(dir, name), 'utf8');
    // A literal "</script" inside an inlined script would end the <script> element early.
    if (/<\/script/i.test(code)) throw new Error(`webclient/${dirName}/${name} contains "</script" — it cannot be inlined`);
    // A function replacement: `$&`-style patterns in the code are not expanded.
    return code;
  });
  if (/\/\*@INLINE /.test(html)) throw new Error(`webclient/${dirName}/index.html: an INLINE marker was not replaced`);
  return html;
}

/** Fuel page: the HTML with every INLINE marker replaced by webclient/fuel/<name>. */
function buildFuelHtml(root = ROOT) { return buildInlineHtml('fuel', root); }

/** Pick & Pack page: webclient/pack/{index.html,logic.js,app.js} → one document. */
function buildPackHtml(root = ROOT) { return buildInlineHtml('pack', root); }

function writeModule(outFile, sourceLabel, html) {
  const banner =
    `// AUTO-GENERATED by scripts/build-webclient.js from ${sourceLabel}.\n` +
    `// Do NOT edit by hand — edit ${sourceLabel} and re-run the script\n` +
    '// (or just `npm run dist`, which regenerates this in predist).\n';
  fs.writeFileSync(outFile, banner + 'module.exports = ' + JSON.stringify(html) + ';\n');
}

function main() {
  const viewer = fs.readFileSync(path.join(ROOT, 'webclient', 'index.html'), 'utf8');
  const viewerOut = path.join(ROOT, 'main', 'webclientHtml.js');
  writeModule(viewerOut, 'webclient/index.html', viewer);
  console.log(`[build-webclient] wrote ${path.relative(ROOT, viewerOut)} (${viewer.length} bytes of HTML)`);

  const fuel = buildFuelHtml();
  const fuelOut = path.join(ROOT, 'main', 'fuelWebclientHtml.js');
  writeModule(fuelOut, 'webclient/fuel/', fuel);
  console.log(`[build-webclient] wrote ${path.relative(ROOT, fuelOut)} (${Buffer.byteLength(fuel)} bytes of HTML)`);

  const pack = buildPackHtml();
  const packOut = path.join(ROOT, 'main', 'packWebclientHtml.js');
  writeModule(packOut, 'webclient/pack/', pack);
  console.log(`[build-webclient] wrote ${path.relative(ROOT, packOut)} (${Buffer.byteLength(pack)} bytes of HTML)`);
}

if (require.main === module) main();

module.exports = { buildFuelHtml, buildPackHtml };
